defmodule RengaWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :renga

  # Browser tests drive the app from a separate browser process. This plug
  # joins each request to its test's database transaction using metadata the
  # test puts in the User-Agent header. It is only compiled into test builds.
  if sandbox = Application.compile_env(:renga, :sql_sandbox) do
    plug Phoenix.Ecto.SQL.Sandbox, sandbox: sandbox
  end

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_renga_key",
    signing_salt: "HkNfslBN",
    same_site: "Lax"
  ]

  # Browser tests sign in by writing a session cookie with these options.
  def session_options, do: @session_options

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:user_agent, session: @session_options]],
    longpoll: [connect_info: [:user_agent, session: @session_options]]

  # Agents listen here for job notices (RFD 9). The intake key travels as the
  # auth token, never in the URL; long polling is off because agents only
  # speak WebSocket.
  socket "/api/v1/agent/socket", RengaWeb.AgentSocket,
    auth_token: true,
    websocket: [connect_info: [:x_headers]],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :renga,
    gzip: not code_reloading?,
    only: RengaWeb.static_paths()

  # The design system's bundled fonts (ui/README.md, "Wiring an app").
  plug Plug.Static,
    at: "/",
    from: {:renga_ui, "priv/static"},
    only: ~w(fonts)

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :renga
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint], log: {__MODULE__, :log_level, []}

  plug RengaWeb.Parsers

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug RengaWeb.Router

  @doc """
  The level the request's start and finish are logged at. A provider test
  link carries its bearer token in the path, which is logged before the
  controller can spend it, so those requests are not logged at all. The
  segments are compared decoded, as the router matches them, so an encoded
  spelling of the same route is not logged either.
  """
  def log_level(%Plug.Conn{path_info: [_, _, _ | _] = path_info}) do
    if Enum.map(Enum.take(path_info, 3), &decode_segment/1) == ["users", "providers", "test"],
      do: false,
      else: :info
  end

  def log_level(_conn), do: :info

  defp decode_segment(segment) do
    URI.decode(segment)
  rescue
    ArgumentError -> segment
  end
end
